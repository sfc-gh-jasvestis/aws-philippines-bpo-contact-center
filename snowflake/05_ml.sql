-- Service-level miss risk scoring and service-level alert forecast over the synthetic snapshot.
-- Predicts P(at least one interval below service level for the queue in the next 7 days) per queue and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.SL_MISS_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.QUEUE_AGE_YEARS,
       r.ABANDON_RATE_PCT, r.AVG_HANDLE_MIN,
       AVG(r.ABANDON_RATE_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS ABANDON_RATE_7D,
       SUM(r.SL_MISS_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS MISSES_30D,
       IFF(SUM(r.SL_MISS_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'MISS', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.QUEUE_DAILY r JOIN RAW.QUEUES a ON a.ID = r.ENTITY_ID
-- Site power interruptions are not queue-driven, so they are excluded from training.
WHERE r.MISS_DRIVER <> 'Site power interruption';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.SL_MISS_TRAIN AS
SELECT CATEGORY, RISK_TIER, QUEUE_AGE_YEARS, ABANDON_RATE_PCT, AVG_HANDLE_MIN, ABANDON_RATE_7D, MISSES_30D, LABEL
FROM ML.SL_MISS_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.SL_MISS_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, QUEUE_AGE_YEARS, ABANDON_RATE_PCT, AVG_HANDLE_MIN, ABANDON_RATE_7D, MISSES_30D, LABEL
FROM ML.SL_MISS_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.SL_MISS_MODEL(
  INPUT_DATA => TABLE(ML.SL_MISS_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.SL_MISS_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.SL_MISS_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'QUEUE_AGE_YEARS', QUEUE_AGE_YEARS,
           'ABANDON_RATE_PCT', ABANDON_RATE_PCT, 'AVG_HANDLE_MIN', AVG_HANDLE_MIN,
           'ABANDON_RATE_7D', ABANDON_RATE_7D, 'MISSES_30D', MISSES_30D)):probability:MISS::FLOAT AS P
  FROM ML.SL_MISS_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'MISS', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'MISS', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'MISS', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'MISS', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per queue (label unknown, so excluded from features).
CREATE TABLE ML.SL_MISS_SCORES AS
WITH latest AS (
  SELECT * FROM ML.SL_MISS_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.SL_MISS_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'QUEUE_AGE_YEARS', QUEUE_AGE_YEARS,
           'ABANDON_RATE_PCT', ABANDON_RATE_PCT, 'AVG_HANDLE_MIN', AVG_HANDLE_MIN,
           'ABANDON_RATE_7D', ABANDON_RATE_7D, 'MISSES_30D', MISSES_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:MISS::FLOAT, 4) AS MISS_PROB_7D,
       CASE WHEN P:probability:MISS::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:MISS::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Contact-centre-wide service-level alert forecast (14 days) from the daily series, for workforce planning.
CREATE VIEW ML.DAILY_SL_ALERTS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(SL_ALERT_COUNT)::FLOAT AS SL_ALERT_COUNT
FROM RAW.QUEUE_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.SL_ALERT_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_SL_ALERTS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'SL_ALERT_COUNT'
);

CREATE TABLE ML.SL_ALERT_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS SL_ALERT_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.SL_ALERT_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
