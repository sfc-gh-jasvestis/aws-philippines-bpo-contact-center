-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT queue.ID AS ENTITY_ID, queue.NAME AS ENTITY_NAME,
       queue.REGION, queue.CATEGORY, queue.RISK_TIER, queue.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.INTERVAL_COUNT) AS INTERVAL_COUNT,
       SUM(observation.CONTACT_COUNT) AS CONTACT_COUNT,
       SUM(observation.LABOR_COST_PHP) AS LABOR_COST_PHP,
       SUM(observation.SL_ALERT_COUNT) AS SL_ALERT_COUNT,
       SUM(observation.SL_MISS_COUNT) AS SL_MISS_COUNT,
       SUM(observation.OVERTIME_CALLOUT) AS OVERTIME_CALLOUT_COUNT,
       SUM(observation.REFORECAST_DUE) AS REFORECAST_DUE,
       SUM(observation.REFORECAST_DONE) AS REFORECAST_DONE,
       100.0 * (SUM(observation.INTERVAL_COUNT) - SUM(observation.SL_MISS_COUNT)) / NULLIF(SUM(observation.INTERVAL_COUNT), 0) AS SL_ATTAINMENT_PCT,
       100.0 * SUM(observation.SL_MISS_COUNT) / NULLIF(SUM(observation.SL_ALERT_COUNT), 0) AS ALERT_MISS_PCT,
       100.0 * SUM(observation.REFORECAST_DONE) / NULLIF(SUM(observation.REFORECAST_DUE), 0) AS REFORECAST_PCT,
       AVG(observation.ABANDON_RATE_PCT) AS AVG_ABANDON_RATE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.QUEUE_DAILY observation
JOIN RAW.QUEUES queue ON queue.ID = observation.ENTITY_ID
GROUP BY queue.ID, queue.NAME, queue.REGION, queue.CATEGORY, queue.RISK_TIER, queue.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(CONTACT_COUNT) AS CONTACT_COUNT, SUM(LABOR_COST_PHP) AS LABOR_COST_PHP,
       SUM(SL_ALERT_COUNT) AS SL_ALERT_COUNT, SUM(SL_MISS_COUNT) AS SL_MISS_COUNT,
       100.0 * SUM(SL_MISS_COUNT) / NULLIF(SUM(SL_ALERT_COUNT), 0) AS ALERT_MISS_PCT
FROM RAW.QUEUE_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.MISS_DRIVER_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT MISS_DRIVER, SUM(SL_ALERT_COUNT) AS SL_ALERT_COUNT,
       SUM(SL_MISS_COUNT) AS SL_MISS_COUNT,
       SUM(OVERTIME_CALLOUT) AS OVERTIME_CALLOUT_COUNT,
       SUM(LABOR_COST_PHP) AS EXPOSED_COST_PHP,
       100.0 * SUM(SL_MISS_COUNT) / NULLIF(SUM(SL_ALERT_COUNT), 0) AS ALERT_MISS_PCT
FROM RAW.QUEUE_DAILY
WHERE SL_ALERT_COUNT > 0
GROUP BY MISS_DRIVER;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(INTERVAL_COUNT) AS INTERVALS, SUM(CONTACT_COUNT) AS CONTACTS,
         SUM(SL_ALERT_COUNT) AS ALERTS, SUM(SL_MISS_COUNT) AS MISSES,
         SUM(OVERTIME_CALLOUT) AS CALLOUTS, SUM(LABOR_COST_PHP) AS LABOR_COST_PHP,
         SUM(REFORECAST_DUE) AS REFORECAST_DUE, SUM(REFORECAST_DONE) AS REFORECAST_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.QUEUE_DAILY
), book AS (SELECT COUNT(*) AS QUEUE_COUNT FROM RAW.QUEUES),
skills AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.AGENT_SKILLS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Service Level Attainment' AS TITLE,
         100.0 * (INTERVALS - MISSES) / NULLIF(INTERVALS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Service-Level Alerts', ALERTS, '' FROM observations
  UNION ALL SELECT 3, 'Intervals Below Service Level', MISSES, '' FROM observations
  UNION ALL SELECT 4, 'Alert Miss Rate', 100.0 * MISSES / NULLIF(ALERTS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Overtime Call-outs', CALLOUTS, '' FROM observations
  UNION ALL SELECT 6, 'Agent Labor Cost (PHP M)', LABOR_COST_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Contacts Offered', CONTACTS, '' FROM observations
  UNION ALL SELECT 8, 'Reforecast Compliance', 100.0 * REFORECAST_DONE / NULLIF(REFORECAST_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Queues Monitored', QUEUE_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Agent Skill Coverage', COVERAGE_PCT, '%' FROM skills
  UNION ALL SELECT 11, 'Agents In Nesting', PENDING, '' FROM skills
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.MISS_DRIVER_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
